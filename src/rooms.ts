/**
 * Уровни — это ДАННЫЕ, а не код. ASCII-карта 40x23 тайла на комнату.
 *
 *   #  тюбинг / бетон (сплошной)
 *   .  пусто
 *   ^  арматура — смерть при касании
 *   ~  фон: зона радиации, счётчик набирается за RAD_DEATH_TIME секунд
 *   c  гнилая шпала — держит CRUMBLE_DELAY секунд после того, как наступил
 *   L  натриевая лампа — статичный источник света
 *   M  упырь    — крадётся в темноте, отступает в луче фонаря
 *   W  горбун   — медленный и тяжёлый, но достаёт с большего расстояния
 *   B  нетопырь — быстрый, рыскающий, зато труслив: луч отгоняет мгновенно
 *   D  дрезина — старт платформы; ходит по коридору из символов `=`
 *   =  рельсовый коридор для дрезины (сам по себе пустой)
 *   G  гермозатвор — столбец двери, циклично закрывается
 *   o  батарея — восполняет рывок в воздухе
 *   P  точка спавна
 *   E  выход из метро (финиш)
 *
 * ГЛАВНОЕ ПРАВИЛО КОМПОЗИЦИИ: игровое пространство ВЫРЕЗАНО В ПОРОДЕ, а не
 * подвешено в пустоте. Верх карты — сплошной массив с неровной нижней кромкой,
 * поэтому у комнаты есть свод, а у платформинга — потолок и силуэт. Пустое небо
 * над уровнем читается как недоделанная заготовка, сколько его ни освещай.
 *
 * Лампы вешаем НА УРОВНЕ ИГРЫ, а не под потолком: радиус LAMP_R невелик, и лампа
 * в верхнем ряду освещает только пустоту. Свет должен падать на то, по чему прыгают.
 *
 * Правая граница комнаты, открытая (символ `.` в 39-й колонке), — переход
 * в следующую комнату: игрок выбегает за край.
 */

/**
 * Тип сцены задаёт дальний план: перспективу, архитектуру и декор стены.
 * Геометрию игры он не трогает — только то, что видно за ней.
 */
